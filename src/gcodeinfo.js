// Reads what a print actually did, from its G-code:
//   - the full settings Snapmaker Orca embedded (; CONFIG_BLOCK_START ... ; key = value)
//   - the objects on the plate (EXCLUDE_OBJECT_DEFINE NAME=... CENTER=... POLYGON=...)
//   - for a failure region (Z range, optional objects): features, speeds, flow, fan, temperatures and toolheads
//     the printer used there, so troubleshooting can point at the moves that were running when it failed.
const { SCHEMA } = require('./orca-settings');

const FILAMENT_AREA = Math.PI * 0.875 * 0.875;
const LIST_TYPES = new Set(['coFloats', 'coInts', 'coPercents', 'coBools', 'coFloatsOrPercents', 'coPoints', 'coEnums']);

function parseConfigBlock(text) {
  const start = text.lastIndexOf('; CONFIG_BLOCK_START');
  const end = text.lastIndexOf('; CONFIG_BLOCK_END');
  if (start < 0 || end < start) return null;
  const out = {};
  for (const line of text.slice(start, end).split('\n')) {
    const m = /^; ([a-z0-9_]+) = (.*)$/.exec(line.trim());
    if (!m) continue;
    const [, key, raw] = m;
    const s = SCHEMA[key];
    if (s && s.type === 'coStrings') out[key] = raw.split(';');
    else if (s && LIST_TYPES.has(s.type)) out[key] = raw.split(',');
    else out[key] = raw;
  }
  return out;
}

function objectsFromGcode(text) {
  const out = [];
  const head = text.slice(0, Math.min(text.length, 3_000_000));
  for (const m of head.matchAll(/^EXCLUDE_OBJECT_DEFINE NAME=(\S+)(?: CENTER=([-\d.]+),([-\d.]+))?(?: POLYGON=(\[.*\]))?/gm)) {
    let polygon = [];
    try { polygon = m[4] ? JSON.parse(m[4]) : []; } catch {}
    out.push({ name: m[1], center: m[2] ? [+m[2], +m[3]] : null, polygon });
  }
  return out;
}

function headerInfo(text) {
  const h = text.slice(0, 20000) + text.slice(-60000);
  const get = (re) => { const m = re.exec(h); return m ? m[1] : null; };
  const dur = get(/; estimated printing time \(normal mode\) = (.+)/);
  let secs = null;
  if (dur) { secs = 0; for (const [, n, u] of dur.matchAll(/(\d+)\s*([dhms])/g)) secs += +n * { d: 86400, h: 3600, m: 60, s: 1 }[u]; }
  return { estimatedSeconds: secs, grams: get(/; total filament used \[g\] = ([\d.]+)/) ? +get(/; total filament used \[g\] = ([\d.]+)/) : null,
    layers: get(/; total layer number: (\d+)/) ? +get(/; total layer number: (\d+)/) : null, maxZ: get(/; max_z_height: ([\d.]+)/) ? +get(/; max_z_height: ([\d.]+)/) : null,
    slicer: get(/; generated by (.+?) on /) };
}

// Activity inside [zMin, zMax] (and, if given, only inside the named objects).
function regionWindow(text, { zMin = 0, zMax = Infinity, objects = null } = {}) {
  const only = objects && objects.length ? new Set(objects) : null;
  const feats = new Map();
  let z = 0, layerZ = 0, type = 'Other', tool = 0, f = 3000, relE = true, eAbs = 0, x = 0, y = 0;
  let inObj = null, fan = 0, nozzle = {}, bed = null, bedInWindow = null;
  const fans = new Set(), temps = {}, tools = new Set(), layersSeen = new Set();
  let retracts = 0, toolChanges = 0, firstZ = null, lastZ = null, travelMoves = 0;
  const inWindow = () => layerZ >= zMin - 1e-6 && layerZ <= zMax + 1e-6 && (!only || (inObj && only.has(inObj)));
  let pos = 0;
  const len = text.length;
  const cfgStart = text.lastIndexOf('; CONFIG_BLOCK_START');
  const stop = cfgStart > 0 ? cfgStart : len;
  while (pos < stop) {
    let nl = text.indexOf('\n', pos); if (nl < 0) nl = len;
    const line = text.slice(pos, nl); pos = nl + 1;
    const c = line.charCodeAt(0);
    if (c === 59) { // ;
      if (line.startsWith(';Z:')) { layerZ = +line.slice(3); }
      else if (line.startsWith(';TYPE:')) type = line.slice(6).trim();
      continue;
    }
    if (c === 69 && line.startsWith('EXCLUDE_OBJECT_START NAME=')) { inObj = line.slice(26).trim(); continue; }
    if (c === 69 && line.startsWith('EXCLUDE_OBJECT_END')) { inObj = null; continue; }
    if (c === 84 && /^T\d+\s*$/.test(line)) { const t = +line.slice(1); if (t !== tool && layerZ >= zMin && layerZ <= zMax) toolChanges++; tool = t; continue; }
    if (c === 77) { // M
      if (line.startsWith('M83')) relE = true; else if (line.startsWith('M82')) relE = false;
      else if (line.startsWith('M106')) { const s = /S([\d.]+)/.exec(line); const p = /P(\d)/.exec(line); if (s && !p) fan = Math.round(+s[1] / 255 * 100); }
      else if (line.startsWith('M107')) fan = 0;
      else if (line.startsWith('M104') || line.startsWith('M109')) { const s = /S([\d.]+)/.exec(line), t = /T(\d)/.exec(line); if (s) nozzle[t ? +t[1] : tool] = +s[1]; }
      else if (line.startsWith('M140') || line.startsWith('M190')) { const s = /S([\d.]+)/.exec(line); if (s) bed = +s[1]; }
      continue;
    }
    if (c !== 71) continue; // G
    if (line.startsWith('G92')) { const m = /E(-?[\d.]+)/.exec(line); if (m) eAbs = +m[1]; continue; }
    if (!(line.startsWith('G1 ') || line.startsWith('G0 ') || line.startsWith('G2 ') || line.startsWith('G3 '))) continue;
    const semi = line.indexOf(';'); const cmd = semi >= 0 ? line.slice(0, semi) : line;
    let nx = x, ny = y, de = 0, hasE = false;
    for (const part of cmd.split(' ')) {
      const k = part.charCodeAt(0), v = +part.slice(1);
      if (k === 88) nx = v; else if (k === 89) ny = v; else if (k === 90) z = v; else if (k === 70) f = v;
      else if (k === 69) { hasE = true; if (relE) de = v; else { de = v - eAbs; eAbs = v; } }
    }
    const dist = Math.hypot(nx - x, ny - y);
    x = nx; y = ny;
    if (!inWindow()) continue;
    if (hasE && de < 0 && dist === 0) { retracts++; continue; }
    if (!(hasE && de > 0 && dist > 0 && f > 0)) { if (dist > 0) travelMoves++; continue; }
    layersSeen.add(layerZ); if (firstZ == null) firstZ = layerZ; lastZ = layerZ;
    const t = dist / (f / 60), flow = de * FILAMENT_AREA / t, speed = f / 60;
    const fe = feats.get(type) || { time: 0, vol: 0, speeds: [], flows: [] };
    fe.time += t; fe.vol += de * FILAMENT_AREA;
    if (fe.speeds.length < 4000) { fe.speeds.push(speed); fe.flows.push(flow); }
    feats.set(type, fe);
    fans.add(fan); tools.add(tool); temps[`T${tool + 1}`] = nozzle[tool]; if (bedInWindow == null) bedInWindow = bed;
  }
  const pct = (arr, p) => { if (!arr.length) return null; const a = [...arr].sort((m, n) => m - n); return +a[Math.min(a.length - 1, Math.floor(a.length * p))].toFixed(1); };
  const total = [...feats.values()].reduce((s, v) => s + v.time, 0) || 1;
  const layerList = [...layersSeen].sort((a, b) => a - b);
  return {
    zFrom: firstZ, zTo: lastZ, layers: layerList.length,
    layerHeights: [...new Set(layerList.slice(1).map((v, i) => +(v - layerList[i]).toFixed(3)))].slice(0, 6),
    features: [...feats.entries()].map(([name, v]) => ({ name, timeShare: +(v.time / total).toFixed(3), speedMedian: pct(v.speeds, 0.5), speedMax: pct(v.speeds, 0.98), flowP95: pct(v.flows, 0.95) }))
      .sort((a, b) => b.timeShare - a.timeShare).slice(0, 12),
    fanPercent: fans.size ? `${Math.min(...fans)}–${Math.max(...fans)}%` : null, nozzleTemps: temps, bedTemp: bedInWindow, toolheads: [...tools].map(t => `T${t + 1}`),
    retractions: retracts, toolChanges, travelMoves,
  };
}

// The support structures the printer actually laid down, as line segments in plate coordinates
// [x1,y1,z1, x2,y2,z2, ...], plus a parallel list of which segments are support interface. For drawing the
// supports in the troubleshooter so a failed support can be painted. Thinned evenly above maxSegments.
function supportPaths(text, maxSegments = 120000) {
  const segs = [], iface = [];
  let x = 0, y = 0, z = 0, type = '', relE = true, eAbs = 0;
  const cfgStart = text.lastIndexOf('; CONFIG_BLOCK_START');
  const stop = cfgStart > 0 ? cfgStart : text.length;
  let pos = 0;
  while (pos < stop) {
    let nl = text.indexOf('\n', pos); if (nl < 0) nl = text.length;
    const line = text.slice(pos, nl); pos = nl + 1;
    const c = line.charCodeAt(0);
    if (c === 59) { if (line.startsWith(';TYPE:')) type = line.slice(6).trim(); continue; }
    if (c === 77) { if (line.startsWith('M83')) relE = true; else if (line.startsWith('M82')) relE = false; continue; }
    if (c !== 71) continue;
    if (line.startsWith('G92')) { const m = /E(-?[\d.]+)/.exec(line); if (m) eAbs = +m[1]; continue; }
    if (!(line.startsWith('G1 ') || line.startsWith('G0 ') || line.startsWith('G2 ') || line.startsWith('G3 '))) continue;
    const semi = line.indexOf(';'); const cmd = semi >= 0 ? line.slice(0, semi) : line;
    let nx = x, ny = y, nz = z, de = 0, hasE = false;
    for (const part of cmd.split(' ')) {
      const k = part.charCodeAt(0), v = +part.slice(1);
      if (k === 88) nx = v; else if (k === 89) ny = v; else if (k === 90) nz = v;
      else if (k === 69) { hasE = true; if (relE) de = v; else { de = v - eAbs; eAbs = v; } }
    }
    if (hasE && de > 0 && /support/i.test(type) && (nx !== x || ny !== y)) {
      segs.push(x, y, nz, nx, ny, nz);
      iface.push(/interface/i.test(type) ? 1 : 0);
    }
    x = nx; y = ny; z = nz;
  }
  const n = iface.length;
  if (n <= maxSegments) return { segments: Float32Array.from(segs), interface: Uint8Array.from(iface), count: n, total: n };
  const step = n / maxSegments, outS = new Float32Array(maxSegments * 6), outI = new Uint8Array(maxSegments);
  for (let i = 0; i < maxSegments; i++) { const j = Math.floor(i * step); outS.set(segs.slice(j * 6, j * 6 + 6), i * 6); outI[i] = iface[j]; }
  return { segments: outS, interface: outI, count: maxSegments, total: n };
}

module.exports = { parseConfigBlock, objectsFromGcode, headerInfo, regionWindow, supportPaths };
